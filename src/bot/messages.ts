export type InputMode = 'current' | 'destination' | 'find';
export function modeHint(mode?: string): string {
  if (mode === 'current') return 'Сейчас ожидаю твоё текущее место.';
  if (mode === 'destination') return 'Сейчас ожидаю новое направление поездки.';
  if (mode === 'find') return 'Для нового поиска напиши другое место.';
  return '';
}

export function errorText(error: unknown, action?: string): string {
  if (error instanceof LocationError) {
    if (error.code === 'invalid_input') return TEXT.input;
    if (error.code === 'not_found') return '<b>Не удалось найти это место</b>\n\nПроверь название или добавь регион либо страну.\nНапример: Брест, Беларусь.';
    if (error.code === 'no_location') return TEXT.noLocation;
    if (error.code === 'geocoding_failed') return action === 'location'
      ? '<b>Не удалось определить место по геолокации</b>\n\nПопробуй отправить её ещё раз или напиши город, регион либо страну.'
      : '<b>Сейчас не получается найти место</b>\n\nПопробуй ещё раз чуть позже.';
    if (error.code === 'unavailable' && ['save', 'delete', 'location'].includes(action ?? '')) {
      return '<b>Не удалось сохранить изменения</b>\n\nПопробуй ещё раз чуть позже.';
    }
  }
  return '<b>Сервис временно недоступен</b>\n\nПопробуй ещё раз чуть позже.';
}
